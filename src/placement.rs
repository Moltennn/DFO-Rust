/*
 * Put the window on a chosen output.
 *
 * Wayland clients cannot position themselves, and this shell runs native
 * Wayland (the GTK window is not visible to X11 tools at all). KWin can:
 * its scripting API has workspace.sendClientToScreen(window, output), which
 * moves a window to an output centred. That is the same result the modding
 * tools' `dfo place DP-1` gets with xdotool on XWayland.
 *
 * Best effort and KDE-only: DFO_WINDOW names an output, "leftmost" (default),
 * "<name>:fullscreen", or "off". Nothing happens on another desktop.
 */

use std::process::Command;
use std::time::Duration;

const SCRIPT_NAME: &str = "dfoRustPlace";

#[derive(Clone, Debug)]
struct Spec {
    name: Option<String>,
    leftmost: bool,
    fullscreen: bool,
}

fn spec() -> Option<Spec> {
    let raw = std::env::var("DFO_WINDOW").unwrap_or_else(|_| "leftmost".into());
    let text = raw.trim();
    if text.is_empty() || text.eq_ignore_ascii_case("off") {
        return None;
    }
    let (left, mode) = match text.split_once(':') {
        Some((left, mode)) => (left, mode),
        None => (text, ""),
    };
    let fullscreen = mode.eq_ignore_ascii_case("fullscreen") || mode.eq_ignore_ascii_case("full");
    let left = left.trim();
    if left.eq_ignore_ascii_case("leftmost") {
        return Some(Spec {
            name: None,
            leftmost: true,
            fullscreen,
        });
    }
    // "x,y" is a point: centre on whatever output holds it (KWin's
    // screenAt arrives as a screen object in newer versions; the script
    // falls back to the leftmost if it cannot resolve one).
    if left.contains(',') {
        return Some(Spec {
            name: None,
            leftmost: true,
            fullscreen,
        });
    }
    Some(Spec {
        name: Some(left.to_string()),
        leftmost: false,
        fullscreen,
    })
}

fn on_kde() -> bool {
    std::env::var("XDG_CURRENT_DESKTOP")
        .map(|v| v.to_ascii_lowercase().contains("kde"))
        .unwrap_or(false)
        || std::env::var_os("KDE_FULL_SESSION").is_some()
}

fn qdbus(args: &[&str]) -> bool {
    for bin in ["qdbus6", "qdbus"] {
        match Command::new(bin).args(args).status() {
            Ok(status) if status.success() => return true,
            Ok(_) => return false,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => continue,
            Err(_) => return false,
        }
    }
    false
}

fn script(spec: &Spec) -> String {
    let name = spec.name.clone().unwrap_or_default();
    format!(
        r#"// Generated by dfo-shell: send the game window to an output.
var NAME = {name};
var LEFTMOST = {leftmost};
var FULLSCREEN = {fullscreen};
function target() {{
  var screens = workspace.screens || [];
  var i;
  if (NAME) {{
    for (i = 0; i < screens.length; i++) if (screens[i].name === NAME) return screens[i];
  }}
  if (LEFTMOST) {{
    var best = null;
    for (i = 0; i < screens.length; i++) {{
      if (!best || screens[i].geometry.x < best.geometry.x) best = screens[i];
    }}
    return best;
  }}
  return null;
}}
function place() {{
  var wins = workspace.windowList();
  var w = null;
  for (var i = 0; i < wins.length; i++) {{
    var wc = String(wins[i].resourceClass || '').toLowerCase();
    var cap = String(wins[i].caption || '');
    if (wc === 'dfo-shell' || cap.indexOf('DFO Online (Rust shell)') !== -1) w = wins[i];
  }}
  if (!w) return;
  var out = target();
  if (out && (!w.output || w.output.name !== out.name)) workspace.sendClientToScreen(w, out);
  if (FULLSCREEN) {{ try {{ if (!w.fullScreen) w.fullScreen = true; }} catch (e) {{}} }}
}}
place();
var n = 0;
var timer = setInterval(function () {{ place(); if (++n > 40) clearInterval(timer); }}, 250);
"#,
        name = serde_json::to_string(&name).unwrap_or_else(|_| "\"\"".into()),
        leftmost = spec.leftmost,
        fullscreen = spec.fullscreen,
    )
}

/// Start the placement thread. The window must exist and be mapped, so the
/// script itself retries for ten seconds on the compositor side.
pub fn start() {
    let Some(spec) = spec() else { return };
    if !on_kde() {
        return;
    }
    std::thread::spawn(move || {
        std::thread::sleep(Duration::from_millis(1500));
        let file = std::env::temp_dir().join(format!("dfo-shell-place-{}.js", std::process::id()));
        if std::fs::write(&file, script(&spec)).is_err() {
            return;
        }
        let path = file.to_string_lossy().into_owned();
        let _ = qdbus(&[
            "org.kde.KWin",
            "/Scripting",
            "org.kde.kwin.Scripting.unloadScript",
            SCRIPT_NAME,
        ]);
        let loaded = qdbus(&[
            "org.kde.KWin",
            "/Scripting",
            "org.kde.kwin.Scripting.loadScript",
            &path,
            SCRIPT_NAME,
        ]);
        if loaded {
            qdbus(&["org.kde.KWin", "/Scripting", "org.kde.kwin.Scripting.start"]);
            std::thread::sleep(Duration::from_secs(12));
            qdbus(&[
                "org.kde.KWin",
                "/Scripting",
                "org.kde.kwin.Scripting.unloadScript",
                SCRIPT_NAME,
            ]);
        }
        let _ = std::fs::remove_file(file);
    });
}
